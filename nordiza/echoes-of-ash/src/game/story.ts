export function determineEnding(
  stats: GameStats,
  finalChoice: string,
): Ending {
  if (finalChoice === 'kill-malek') {
    return {
      id: 'ash-of-vengeance',
      title: 'رماد الانتقام',
      condition: 'قتل مالك',
      text: [
        'سقط مالك على سطح البرج. انقسمت المدينة بين الاحتفال والخوف.',
        stats.evidence >= 6
          ? 'استمر كشف الحقيقة، وتمت محاكمة بقية المتورطين.'
          : 'استغل أتباع مالك موته لمحو جرائمه وتصوير آدم كقاتل دمّر فرصة المدينة في المعرفة.',
        'عاد آدم إلى الغابة وحده. جلس قرب النهر حتى الصباح.',
        '"انتهى" — قالها بصوت مكسور. لكن صوت ليان بقي يردد: "لا تجعل ما حدث لنا هو كل ما تبقى منك."',
        stats.trust >= 4
          ? 'ظهرت مريم وجابر. لم يديناه. حملا معه الطائر الخشبي ومشيا نحو الفجر.'
          : 'مشى وحده. حصل على انتقامه كاملاً، وكان كماله أكثر ما أخافه فيه.',
      ],
    };
  }

  if (stats.evidence >= 7 || stats.mercy >= 8) {
    return {
      id: 'dawn-erases-night',
      title: 'فجر لا يمحو الليل',
      condition: 'اعتقال مالك + أدلة قوية',
      text: [
        'بدأت محاكمة علنية. أدلى الشهود بشهاداتهم أمام العالم.',
        'قرأت أم عمر اسم ابنها أمام الكاميرات. شهدت نهى، واعترف الصقر.',
        '"هذه القضية لا تتعلق بمدينة وجدت وحشاً في الغابة." — مريم',
        '"إنها تتعلق بمدينة سمحت لوحش أن يجلس خلف مكتب، لأنه وعدها بأسوار أعلى."',
        'بعد أشهر، زار آدم قبر ليان ويزن. وضع الطائر الخشبي بينهما بعد أن أضاف جناحاً ثانياً.',
        '"العدالة لم تعد الموتى، لكنها منعت الموتى من أن يكونوا آخر من يتكلم."',
      ],
    };
  }

  return {
    id: 'wounded-truth',
    title: 'الحقيقة الجريحة',
    condition: 'اعتقال مالك + أدلة ناقصة',
    text: [
      'أفلت عدد من شركاء مالك باستغلال نقص الأدلة.',
      'استمرت المحاكمة، لكن الانقسامات ظهرت في المدينة.',
      '"الحقيقة لا تجبر أحداً على النظر." — آدم',
      'في المشهد الأخير، وصل طفل ناجٍ إلى نصب الضحايا وجلس بجانب آدم.',
      '"هل انتهى الأمر؟" — "لا." — "فلماذا يقولون إننا انتصرنا؟"',
      '"لأنهم يريدون نهاية مريحة. نحن ما زلنا نعمل على النهاية الحقيقية."',
    ],
  };
}
